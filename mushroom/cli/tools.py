# -*- coding: utf-8 -*-
"""Commands not bound to a particular code

Modules heavier than click are imported inside the commands to keep the entry fast.
"""
import sys

import click

from mushroom.cli._utils import MultiValueCommand, check_exclusive, multi_option, optional_value_option

# same as mushroom.core.eos.available_eos, which is not imported here to keep the entry fast
_AVAILABLE_EOS = ("bm", "m")


# pylint: disable=R0914
def _export_fitted(popt, pcov, vols, vfit, enes, efit, eosname, output):
    """export fitted data, shift energy zero to E0"""
    import numpy as np

    from mushroom.core.constants import EV_PER_ANG_CUB2GPA
    from mushroom.core.eos import get_eos

    eosfunc, shortname, _ = get_eos(eosname)
    perr = np.sqrt(np.diag(pcov))
    conv = EV_PER_ANG_CUB2GPA
    print("Fitting {} EOS".format(shortname))
    print("  E0 = {:13.5f} ({:9.5f})".format(popt[0], perr[0]))
    print("  V0 = {:13.5f} ({:9.4f})".format(popt[1], perr[1]))
    # modulus, converting eV/A^3 to GPa needs a factor of ~160
    print("  B0 = {:13.3f} ({:9.3f})".format(popt[2] * conv, perr[2] * conv))
    if len(popt) > 3:
        print("  Bp = ", popt[3])

    efit -= popt[0]
    enes -= popt[0]

    R2 = 1 - np.sum((enes - eosfunc(vols, *popt))**2) / np.sum((enes - np.mean(enes))**2)

    with open(output, 'w') as h:
        def p(x):
            print(x, file=h)
        p("#Data generated by: {}".format(" ".join(sys.argv)))
        p("#Fitted {} EOS data, shifted zero to E0".format(eosname))
        p("#E0(eV) {} stderr {}".format(popt[0], perr[0]))
        p("#V0(A3) {} stderr {}".format(popt[1], perr[1]))
        p("#B0(eV/A3) {} stderr {}".format(popt[2], perr[2]))
        p("#B0(GPa) {} stderr {}".format(popt[2] * conv, perr[2] * conv))
        p("#other parameters: {} stderr {}".format(popt[3:], perr[3:]))
        p("#R2: {}".format(R2))
        for v, e in zip(vfit, efit):
            p("{:15.6f} {:15.6f}".format(v, e))
        p("")
        p("#Shifted original data")
        for v, e in zip(vols, enes):
            p("{:15.6f} {:15.6f}".format(v, e))


# pylint: disable=W0632
@click.command(cls=MultiValueCommand)
@click.argument("input_file", metavar="INPUT")
@click.option("-n", "nfu", type=int, default=1, help="number of formula units")
@click.option("-v", "v0", type=float, default=None, help="initial guess of ground state volume V0")
@click.option("-e", "e0", type=float, default=None, help="initial guess of ground state energy E0")
@click.option("--eos", "eosname", type=click.Choice(_AVAILABLE_EOS), default="bm",
              help="type of EOS, default using Birch-Murnaghan (bm)")
@click.option("--vc", "ivcol", type=int, default=1, help="column index of volume data. Default 1")
@click.option("--ec", "iecol", type=int, default=2, help="column index of energy data. Default 2")
def fiteos(input_file, nfu, v0, e0, eosname, ivcol, iecol):
    """Auto non-linear fitting of Equation of State.

    Four argument is needed: data file, number of formula units, E0 and V0.

    The data file should have volume and energy data columns.
    The default indices of volume and energy columns are 1 and 2, respectively (starting from 1).
    They can be specified by option ``--vc`` and ``--ec``.

    For now, eV and Angstrom^3 are assumed as units.

    The last two can be extracted by figuring out the lowest point among the data, if not specified.
    """
    import numpy as np
    from scipy.optimize import curve_fit

    from mushroom.core.eos import get_eos

    # initialization
    b0 = 1.0
    bp = 4.0
    vols, enes = np.loadtxt(input_file, unpack=True, usecols=(ivcol - 1, iecol - 1))

    if nfu != 1:
        vols /= nfu
        enes /= nfu

    if e0 is None:
        e0 = min(enes)
    # volume of the data point closest to the guess of E0
    v0_guess = vols[np.argmin(np.abs(enes - e0))]
    if v0 is not None:
        v0_guess = v0

    eosfunc, _, _ = get_eos(eosname)
    popt, pcov = curve_fit(eosfunc, vols, enes, p0=[e0, v0_guess, b0, bp], maxfev=5000)

    # write fitted data
    vfit = np.linspace(0.98 * min(vols), 1.02 * max(vols), 100)
    efit = eosfunc(vfit, *popt)

    _export_fitted(popt, pcov, vols, vfit, enes, efit, eosname=eosname,
                   output=input_file + "_fitted")


# pylint: disable=R0912,R0914,R0915
@click.command(cls=MultiValueCommand)
@click.argument("data_files", nargs=-1, required=True)
@click.option("-t", "title", default=None, help="title that will be parsed to the first graph")
@click.option("--xl", "xlabel", default=None, help="x label")
@click.option("--xr", "xrange", default=None, help="x range, e.g. 'm8~5' for -8.0 to 5.0")
@click.option("--yl", "ylabel", default=None, help="y label")
@click.option("--lw", "linewidth", type=float, default=None, help="line width")
@click.option("-c", "color", default=None, help="color code")
@click.option("--yr", "yrange", default=None, help="same as --xr, for y range")
@optional_value_option("-s", "symbol", const="", default="none", help="symbol")
@click.option("--xscale", type=click.Choice(["log", "rec"]), default=None, help="X scale")
@click.option("--yscale", type=click.Choice(["log", "rec"]), default=None, help="Y scale")
@click.option("-o", "output", default=None, help="output agr filename")
@click.option("-d", "delimiter", default=None, help="delimiter parsed to numpy.loadtxt")
@click.option("--no-label", is_flag=True, help="insert legend to dataset comment, not to label")
@click.option("-x", "ix", type=int, default=0, help="xcol")
@multi_option("--xy", metavar="XCOL:YCOL...", help="xcol:ycol")
@multi_option("--xyz", metavar="XCOL:YCOL:ZCOL...", help="xcol:ycol:zcol")
@click.option("--sort", is_flag=True, help="sort: X not supported, Y for cols=1")
@click.option("--l-comment", "leg_comment", is_flag=True,
              help="use comment line (starting exactly # and single space) above the data session")
@click.option("--l-add-fn", "leg_add_fn", is_flag=True, help="add filename to legend")
@click.option("--l-fn-only", "leg_fn_only", is_flag=True, help="only use filename as legend")
@multi_option("--l-exp", "leg_explicit", metavar="LEGEND...",
              help="explicit legend; match number of datasets, default if missing")
@click.pass_context
def quickgrace(ctx, data_files, title, xlabel, xrange, ylabel, linewidth, color, yrange, symbol,
               xscale, yscale, output, delimiter, no_label, ix, xy, xyz, sort, leg_comment,
               leg_add_fn, leg_fn_only, leg_explicit):
    r"""draw grace plot quickly from data files, using np.loadtxt

    Column index starts from 0. Allow dataset separated by empty lines.
    Support multiple data files.
    Note that the generated file is rough.

    \b
    Current caveat:
      - single graph only
      - all data will be read and processed later
      - only support index-y or xy. no xyz or xysize

    Note that linewidth, color and symbol will be set for all datasets
    """
    import warnings
    from io import StringIO

    import numpy as np

    from mushroom.core.ioutils import decode_float_ends, get_filename_wo_ext, readtext_split_emptyline
    from mushroom.visual.graceplot import Plot

    check_exclusive(ctx, "ix", "xy", "xyz")
    check_exclusive(ctx, "leg_comment", "leg_add_fn", "leg_fn_only", "leg_explicit")
    # no value after -s means to use the default symbol of the plotter
    symbol = symbol or None

    fig, ax = Plot.subplots(1, 1)
    ax.set_title(title=title)
    ax.set_xlabel(xlabel)
    ax.set_ylabel(ylabel)

    legends_comments = []
    for fn in data_files:
        with open(fn, 'r') as h:
            legends_comments.extend(x[2:].strip() for x in h.readlines() if x.startswith("# "))

    # a generator to find explicit legend, None if exhausted
    def get_explict_legend():
        for leg in leg_explicit:
            yield leg
        if leg_comment:
            for leg in legends_comments:
                yield leg
        while True:
            yield None

    legends = get_explict_legend()

    def default_legend(fn, *cols):
        """legend from filename and column indices"""
        scols = ":".join(str(x) for x in cols)
        if leg_add_fn:
            return "{}:{}".format(fn, scols)
        if leg_fn_only:
            return fn
        return scols

    warnings.filterwarnings('ignore', r'loadtxt: Empty input file')

    for fn in data_files:
        datastrings = readtext_split_emptyline(fn)

        for s in datastrings:
            data_cols = np.loadtxt(StringIO(s), unpack=True, ndmin=2, delimiter=delimiter)
            ncols = len(data_cols)
            # no data
            if ncols == 0:
                continue
            kwargs = {"symbol": symbol, "lw": linewidth, "color": color}
            # only one data column, plot it against index (starting from 1)
            if ncols == 1:
                if sort:
                    data_cols[0].sort()
                legend = next(legends)
                label = None if no_label else legend
                ax.plot(list(range(1, len(data_cols[0]) + 1)), data_cols[0], label=label,
                        comment=legend, **kwargs)
                continue
            if xy:
                for pair in xy:
                    icols = tuple(map(int, pair.split(':')))
                    ix_pair, iy = icols
                    legend = next(legends)
                    if legend is None:
                        legend = default_legend(fn, *icols)
                    label = None if no_label else legend
                    ax.plot(data_cols[ix_pair], data_cols[iy], label=label, comment=legend, **kwargs)
                continue
            if xyz:
                for triple in xyz:
                    icols = tuple(map(int, triple.split(':')))
                    ix_triple, iy, iz = icols
                    legend = next(legends)
                    if legend is None:
                        legend = default_legend(fn, *icols)
                    label = None if no_label else legend
                    ax.plot(data_cols[ix_triple], data_cols[iy], data_cols[iz], label=label,
                            comment=legend, **kwargs)
                continue
            for iy in range(ncols):
                # skip plotting against itself
                if iy == ix:
                    continue
                legend = next(legends)
                if legend is None:
                    legend = default_legend(fn, ix, iy)
                label = None if no_label else legend
                ax.plot(data_cols[ix], data_cols[iy], label=label, comment=legend, **kwargs)

    if xrange is not None:
        ax.set_xlim(*decode_float_ends(xrange))
    if yrange is not None:
        ax.set_ylim(*decode_float_ends(yrange))
    if xrange is None and yrange is None:
        fig.tight_graph()

    if xscale is not None:
        ax.set_xscale(xscale)
    if yscale is not None:
        ax.set_yscale(yscale)

    if output is None:
        output = get_filename_wo_ext(data_files[0]) + "_quickgp.agr"
    fig.write(output)
